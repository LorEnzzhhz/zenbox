#!/usr/bin/env node
// Push this project's source to a GitHub repo via the Contents API so the
// Actions workflow can build both APKs from the repo alone.
//
// Usage: GITHUB_TOKEN=ghp_xxx node scripts/gh-push-source.mjs <owner/repo>
//
// Excludes build artifacts / machine files; INCLUDES src/convex/_generated
// (the workflow needs it to typecheck) and public/linux (needed by the APKs).
// Re-runnable: existing files are updated in place.

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const repo = process.argv[2];
const token = process.env.GITHUB_TOKEN;
if (!token) {
  console.error("Missing GITHUB_TOKEN.");
  process.exit(1);
}
if (!/^[\w.-]+\/[\w.-]+$/.test(repo ?? "")) {
  console.error("Usage: GITHUB_TOKEN=ghp_xxx node scripts/gh-push-source.mjs <owner/repo>");
  process.exit(1);
}

const ROOT = process.cwd();

// Paths that must NOT be pushed (build outputs, machine files, VCS).
const SKIP_DIRS = new Set([
  ".git",
  "node_modules",
  "dist",
  "dist-control",
  "build",
  ".gradle",
  ".idea",
  ".vscode",
  ".cache",
  "coverage",
]);
const SKIP_FILES = new Set([
  "local.properties",
  ".env",
  ".env.local",
  ".env.production",
  "keystore.properties",
  "*.keystore",
]);
const SKIP_FILE_SUFFIXES = [".keystore", ".jks"];
// Path prefixes that must NOT be pushed: built APKs, cap-sync output copied
// into the android projects (regenerated by `cap sync` in CI), and the
// generated capacitor-cordova plugin bridges.
const SKIP_PATH_PREFIXES = [
  "apk/",
  "android/app/src/main/assets/",
  "android-control/android/app/src/main/assets/",
  "android/capacitor-cordova-android-plugins/",
  "android-control/capacitor-cordova-android-plugins/",
];
// Contents API limit: ~95 MB raw per file (base64 expands 1.33x).
const MAX_FILE_BYTES = 95 * 1024 * 1024;

const files = [];
function walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(full);
    } else if (entry.isFile()) {
      const rel = relative(ROOT, full).split(sep).join("/");
      if (SKIP_FILES.has(rel)) continue;
      if (SKIP_FILE_SUFFIXES.some((s) => rel.endsWith(s))) continue;
      if (SKIP_PATH_PREFIXES.some((p) => rel.startsWith(p))) continue;
      const size = statSync(full).size;
      if (size > MAX_FILE_BYTES) {
        console.log(`skip (too large): ${rel} (${(size / 1048576).toFixed(1)} MB)`);
        continue;
      }
      files.push({ rel, full });
    }
  }
}
walk(ROOT);

console.log(`Pushing ${files.length} files to ${repo}…`);

const headers = {
  Authorization: `Bearer ${token}`,
  Accept: "application/vnd.github+json",
  "X-GitHub-Api-Version": "2022-11-28",
  "User-Agent": "zenbox-source-push",
};

async function put(path, body) {
  const res = await fetch(`https://api.github.com/repos/${repo}/contents/${encodeURIComponent(path)}`, {
    method: "PUT",
    headers,
    body: JSON.stringify(body),
  });
  return res;
}

let ok = 0;
let failed = 0;
let already = 0;
for (const { rel, full } of files) {
  try {
    const data = readFileSync(full);
    const content = data.toString("base64");
    // Existing file? Contents API needs the current sha to update.
    let sha = null;
    const head = await fetch(`https://api.github.com/repos/${repo}/contents/${encodeURIComponent(rel)}`, { headers });
    if (head.ok) {
      const existing = await head.json();
      sha = existing.sha ?? null;
      // Unchanged on the remote already — skip to stay fast and avoid churn.
      if (existing.content === content) {
        already++;
        continue;
      }
    }
    const res = await put(rel, {
      message: `Sync ${rel} from Zenbox source`,
      content,
      ...(sha ? { sha } : {}),
    });
    if (res.ok || res.status === 201) {
      ok++;
    } else {
      let msg = `HTTP ${res.status}`;
      try {
        msg = (await res.json()).message ?? msg;
      } catch {
        /* ignore */
      }
      console.error(`✗ ${rel}: ${msg}`);
      failed++;
    }
  } catch (err) {
    console.error(`✗ ${rel}: ${err instanceof Error ? err.message : "error"}`);
    failed++;
  }
}

console.log(`\nDone: ${ok} pushed, ${already} already up to date, ${failed} failed.`);
if (failed > 0) process.exit(1);
